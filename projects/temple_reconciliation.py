"""Reconcile independently verified temple events against the actual published ICS.

OCR-only image/PDF discoveries are a *review queue*, never verified events.
For hard failures, use curated events and an explicitly maintained flyer ledger.
Only compare current events and never manufacture a date from a yearless flyer.
"""
from __future__ import annotations

from collections import Counter
from datetime import date, datetime, timezone
from difflib import SequenceMatcher
from urllib.parse import urlsplit
from zoneinfo import ZoneInfo
import re

TZ = ZoneInfo("America/Phoenix")


def _title(value):
    return " ".join(re.findall(r"[a-z0-9]+", str(value).casefold()))


def _unescape(value):
    return (value.replace(r"\n", "\n").replace(r"\N", "\n")
            .replace(r"\,", ",").replace(r"\;", ";").replace(r"\\", "\\"))


def read_ics_events(data):
    """Read calendar events from RFC5545-style folded ICS generated by this hub."""
    text = data.decode("utf-8") if isinstance(data, bytes) else data
    lines = re.sub(r"\r?\n[ \t]", "", text).splitlines()
    events, row = [], None
    for line in lines:
        if line == "BEGIN:VEVENT":
            row = {}
        elif line == "END:VEVENT":
            if row is not None:
                events.append(row)
            row = None
        elif row is not None and ":" in line:
            left, value = line.split(":", 1)
            name = left.split(";", 1)[0].upper()
            if name == "SUMMARY":
                row["title"] = _unescape(value)
            elif name == "DTSTART":
                if "VALUE=DATE" in left.upper():
                    row["date"] = date.fromisoformat(
                        value[:4] + "-" + value[4:6] + "-" + value[6:8]).isoformat()
                    row["time"] = None
                else:
                    parsed = datetime.strptime(value, "%Y%m%dT%H%M%SZ").replace(tzinfo=timezone.utc)
                    local = parsed.astimezone(TZ)
                    row["date"] = local.date().isoformat()
                    row["time"] = local.strftime("%H:%M")
            elif name in ("UID", "LOCATION", "URL"):
                row[name.lower()] = _unescape(value)
    return events


def _expected_from_registry(manifest, now):
    expected = {}
    current = now.astimezone(TZ).date()
    for item in manifest.get("events", []):
        d = item["start"][:10]
        if d < current.isoformat() and item.get("end", "")[:10] <= current.isoformat():
            continue
        entry = {
            "title": item["title"], "date": d,
            "time": item["start"][11:16] if "T" in item["start"] else None,
            "kind": "curated_manifest", "source_url": item.get("url", ""),
        }
        expected[(_title(entry["title"]), d)] = entry
    for item in manifest.get("verified_flyer_events", []):
        if item["date"] < current.isoformat():
            continue
        entry = {
            "title": item["calendar_title"], "date": item["date"],
            "time": item.get("start_time"),
            "kind": "independently_verified_flyer",
            "source_url": item["source_url"],
            "source_name": item.get("source_name", ""),
        }
        expected[(_title(entry["title"]), entry["date"])] = entry
    return list(expected.values())


def _match_expected(expected, actual):
    return (expected["date"] == actual.get("date")
            and _title(expected["title"]) == _title(actual.get("title", "")))


def _similar(a, b):
    first, second = _title(a), _title(b)
    if not first or not second:
        return 0.0
    if first in second or second in first:
        return 0.9
    aa, bb = set(first.split()), set(second.split())
    return max(len(aa & bb) / max(1, len(aa | bb)),
               SequenceMatcher(None, first, second).ratio())


def _review_ocr(candidates, actual):
    """Do not conflate OCR guesses with independently verified omissions."""
    review = []
    for candidate in candidates:
        d = candidate.get("date")
        source_host = urlsplit(candidate.get("origin", "")).hostname or ""
        possible = [ev for ev in actual if (not d or ev.get("date") == d)]
        if source_host:
            related = [ev for ev in possible if (
                source_host == (urlsplit(ev.get("url", "")).hostname or "")
                or source_host.endswith(".ektamandiraz.org") and "ekta mandir" in ev.get("title", "").casefold()
                or "squarespace" in source_host and "maha ganapati" in ev.get("title", "").casefold())]
            if related:
                possible = related
        rated = sorted(((_similar(candidate.get("title", ""), ev.get("title", "")), ev)
                        for ev in possible), key=lambda x: x[0], reverse=True)
        best = rated[0] if rated else None
        if not d:
            status = "date_unverified"
        elif best and best[0] >= 0.65:
            status = "likely_covered_needs_review"
        else:
            status = "possible_missing_needs_review"
        review.append({
            "status": status, "date": d, "title": candidate.get("title", ""),
            "image_or_pdf_url": candidate.get("origin", ""),
            "likely_calendar_match": best[1].get("title") if best and best[0] >= 0.65 else None,
        })
    return review


def reconcile(manifest, ics_bytes, now, source_audits=None):
    """Compare a verified source ledger to real ICS entries; report, don't auto-add."""
    actual = read_ics_events(ics_bytes)
    expected = _expected_from_registry(manifest, now)
    matched, missing, time_conflicts, duplicates = [], [], [], []
    for entry in expected:
        hits = [ev for ev in actual if _match_expected(entry, ev)]
        if not hits:
            missing.append(entry)
        elif len(hits) > 1:
            duplicates.append({"expected": entry, "found": len(hits),
                               "calendar_times": [x.get("time") for x in hits]})
        elif entry["time"] is not None and hits[0].get("time") != entry["time"]:
            time_conflicts.append({"expected": entry,
                                   "calendar_time": hits[0].get("time"),
                                   "expected_time": entry["time"]})
        else:
            matched.append(entry)
    # Detect duplicate ICS entries even when no flyer-ledger entry exists.
    keys = Counter((ev.get("date"), _title(ev.get("title", ""))) for ev in actual)
    for (d, title), number in keys.items():
        if number > 1 and not any(_title(e["expected"]["title"]) == title
                                  and e["expected"]["date"] == d for e in duplicates):
            duplicates.append({"title": title, "date": d, "found": number})
    source_audits = source_audits or []
    candidates = [c for row in source_audits for c in row.get("candidates", [])]
    ocr_review = _review_ocr(candidates, actual)
    source_gaps = [{
        "source": row.get("name"), "url": row.get("url"),
        "status": row.get("status"), "warnings": row.get("warnings", []),
    } for row in source_audits if row.get("status") in ("partial", "blocked", "error", "incomplete", "outdated")
       or row.get("warnings")]
    failures = len(missing) + len(duplicates) + len(time_conflicts)
    return {
        "schema_version": 1, "generated_utc": now.astimezone(timezone.utc).isoformat(),
        "verified_expected": len(expected), "matched": len(matched),
        "missing": missing, "duplicates": duplicates, "time_conflicts": time_conflicts,
        "verified_failures": failures, "verified_passed": failures == 0,
        "ocr_candidate_count": len(ocr_review),
        "ocr_review": ocr_review, "source_coverage_gaps": source_gaps,
        "note": ("Verified entries are compared to actual generated ICS, including clock time; "
                 "OCR-only candidates are unverified and NEVER auto-published. "
                 "No missing event is assumed from a blocked or stale source."),
    }
